	<!-- wp:heading {"anchor":"malaria","className":"gcp-icon gcp-icon-test"} -->
	<h2 class="wp-block-heading gcp-icon gcp-icon-test" id="malaria">Malaria: prevent it, and test before you treat</h2>
	<!-- /wp:heading -->
	<!-- wp:paragraph -->
	<p>Malaria spreads through mosquito bites, mostly at night. Children under five and pregnant women are at the highest risk of severe illness.</p>
	<!-- /wp:paragraph -->
	<!-- wp:list -->
	<ul class="wp-block-list">
		<!-- wp:list-item -->
		<li>Sleep under an insecticide-treated mosquito net every night, all year round.</li>
		<!-- /wp:list-item -->
		<!-- wp:list-item -->
		<li>Clear standing water around your home, where mosquitoes breed.</li>
		<!-- /wp:list-item -->
		<!-- wp:list-item -->
		<li>If you have a fever, chills, headache or body pains, get tested within 24 hours. A rapid test takes minutes.</li>
		<!-- /wp:list-item -->
		<!-- wp:list-item -->
		<li>If the test is positive, take the full course of treatment, even when you feel better after a day or two.</li>
		<!-- /wp:list-item -->
	</ul>
	<!-- /wp:list -->
	<!-- wp:paragraph {"className":"gcp-alert"} -->
	<p class="gcp-alert"><strong>Go to a hospital now</strong> if someone with fever has convulsions, cannot drink, is very sleepy or confused, has yellow eyes, or passes dark urine.</p>
	<!-- /wp:paragraph -->

	<!-- wp:heading {"anchor":"blood-pressure","className":"gcp-icon gcp-icon-bp"} -->
	<h2 class="wp-block-heading gcp-icon gcp-icon-bp" id="blood-pressure">High blood pressure: the silent condition</h2>
	<!-- /wp:heading -->
	<!-- wp:paragraph -->
	<p>Most people with high blood pressure feel completely well, which is why regular checks matter. Readings of 140/90 or higher on repeated checks usually mean you should see a doctor.</p>
	<!-- /wp:paragraph -->
	<!-- wp:list -->
	<ul class="wp-block-list">
		<!-- wp:list-item -->
		<li>Use less salt in cooking and avoid adding salt at the table.</li>
		<!-- /wp:list-item -->
		<!-- wp:list-item -->
		<li>Be active for about 30 minutes on most days. A brisk walk counts.</li>
		<!-- /wp:list-item -->
		<!-- wp:list-item -->
		<li>Limit alcohol and stop smoking.</li>
		<!-- /wp:list-item -->
		<!-- wp:list-item -->
		<li>If you are on treatment, take it every day, even when you feel fine. Do not stop without talking to your doctor.</li>
		<!-- /wp:list-item -->
	</ul>
	<!-- /wp:list -->
	<!-- wp:paragraph {"className":"gcp-alert"} -->
	<p class="gcp-alert"><strong>Get urgent help</strong> for a sudden severe headache, chest pain, weakness on one side of the body, difficulty speaking, or blurred vision.</p>
	<!-- /wp:paragraph -->

	<!-- wp:heading {"anchor":"diabetes","className":"gcp-icon gcp-icon-sugar"} -->
	<h2 class="wp-block-heading gcp-icon gcp-icon-sugar" id="diabetes">Diabetes: know the signs, control your sugar</h2>
	<!-- /wp:heading -->
	<!-- wp:paragraph -->
	<p>Common early signs are constant thirst, passing urine often, tiredness, blurred vision and wounds that heal slowly. A simple blood sugar test can check.</p>
	<!-- /wp:paragraph -->
	<!-- wp:list -->
	<ul class="wp-block-list">
		<!-- wp:list-item -->
		<li>Take your medicine exactly as prescribed and keep regular check-ups.</li>
		<!-- /wp:list-item -->
		<!-- wp:list-item -->
		<li>Cut down on sugary drinks and sweets. Fill half your plate with vegetables.</li>
		<!-- /wp:list-item -->
		<!-- wp:list-item -->
		<li>Check your feet every day for cuts, blisters or swelling.</li>
		<!-- /wp:list-item -->
		<!-- wp:list-item -->
		<li>Know the signs of low sugar: shaking, sweating, hunger and confusion. Take something sweet straight away and seek help if it does not improve.</li>
		<!-- /wp:list-item -->
	</ul>
	<!-- /wp:list -->

	<!-- wp:heading {"anchor":"diarrhoea","className":"gcp-icon gcp-icon-family"} -->
	<h2 class="wp-block-heading gcp-icon gcp-icon-family" id="diarrhoea">Diarrhoea in children: replace lost fluids</h2>
	<!-- /wp:heading -->
	<!-- wp:paragraph -->
	<p>The biggest danger of diarrhoea in young children is dehydration. Oral rehydration salts (ORS) replace the water and salts the body loses.</p>
	<!-- /wp:paragraph -->
	<!-- wp:list -->
	<ul class="wp-block-list">
		<!-- wp:list-item -->
		<li>Give ORS after every loose stool, mixed with clean water exactly as the packet says.</li>
		<!-- /wp:list-item -->
		<!-- wp:list-item -->
		<li>Keep breastfeeding and keep offering food.</li>
		<!-- /wp:list-item -->
		<!-- wp:list-item -->
		<li>Ask us about zinc tablets, which help children recover faster.</li>
		<!-- /wp:list-item -->
		<!-- wp:list-item -->
		<li>Wash hands with soap after using the toilet and before preparing food.</li>
		<!-- /wp:list-item -->
	</ul>
	<!-- /wp:list -->
	<!-- wp:paragraph {"className":"gcp-alert"} -->
	<p class="gcp-alert"><strong>Take the child to a health facility</strong> if there is blood in the stool, sunken eyes, repeated vomiting, no urine for many hours, or the child will not drink or is very sleepy.</p>
	<!-- /wp:paragraph -->

	<!-- wp:heading {"anchor":"antibiotics","className":"gcp-icon gcp-icon-rx"} -->
	<h2 class="wp-block-heading gcp-icon gcp-icon-rx" id="antibiotics">Antibiotics: use them right so they keep working</h2>
	<!-- /wp:heading -->
	<!-- wp:list -->
	<ul class="wp-block-list">
		<!-- wp:list-item -->
		<li>Antibiotics treat bacterial infections. They do not work on colds or flu, which are caused by viruses.</li>
		<!-- /wp:list-item -->
		<!-- wp:list-item -->
		<li>Take them only when prescribed, at the times shown on the label.</li>
		<!-- /wp:list-item -->
		<!-- wp:list-item -->
		<li>Finish the whole course. Stopping early helps germs become resistant.</li>
		<!-- /wp:list-item -->
		<!-- wp:list-item -->
		<li>Never save leftovers for later or share them with others.</li>
		<!-- /wp:list-item -->
	</ul>
	<!-- /wp:list -->

	<!-- wp:heading {"anchor":"storage","className":"gcp-icon gcp-icon-shield"} -->
	<h2 class="wp-block-heading gcp-icon gcp-icon-shield" id="storage">Storing medicine at home</h2>
	<!-- /wp:heading -->
	<!-- wp:list -->
	<ul class="wp-block-list">
		<!-- wp:list-item -->
		<li>Keep medicine in a cool, dry place, away from sunlight. Avoid the bathroom, the kitchen stove and a parked car.</li>
		<!-- /wp:list-item -->
		<!-- wp:list-item -->
		<li>Store it in its original packet with the label, so you always know the dose and expiry date.</li>
		<!-- /wp:list-item -->
		<!-- wp:list-item -->
		<li>Keep all medicine high up and out of children's reach.</li>
		<!-- /wp:list-item -->
		<!-- wp:list-item -->
		<li>Check how long a syrup or eye drops last once opened. Bring expired medicine to us for safe disposal.</li>
		<!-- /wp:list-item -->
	</ul>
	<!-- /wp:list -->

